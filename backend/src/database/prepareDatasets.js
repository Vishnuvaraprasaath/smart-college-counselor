// Realistic branch offerings for institutions
const COURSE_MAPPINGS = [];

// Helper to assign verified branches based on institution type and specialty
INSTITUTIONS.forEach(inst => {
  const code = inst.tnea_code;
  const type = inst.institution_type;
  const isAuto = inst.autonomous;

  // Base branches that nearly all established colleges have
  let branches = ['CSE', 'ECE', 'MECH', 'EEE'];

  // Add IT and CIVIL for larger or older colleges
  if (inst.established_year && inst.established_year < 2012) {
    branches.push('IT');
    branches.push('CIVIL');
  }

  // Autonomous and modern colleges have AIDS / AIML / CYBER
  if (isAuto) {
    branches.push('AIDS');
    if (['0001', '0004', '2006', '2007', '2712', '2718', '2702', '2711', '1211', '1315', '2751', '2739'].includes(code)) {
      branches.push('AIML');
      branches.push('CYBER');
    }
  }

  // Specialized departments
  if (['0002', '2006', '2007', '2711', '1219', '1315'].includes(code)) branches.push('CHEM');
  if (['0002', '1211', '2702', '2712', '4965', '1317', '3011'].includes(code)) branches.push('BT');
  if (['0001', '1315', '1211', '2006', '2715', '5910'].includes(code)) branches.push('BM');
  if (['0004', '2006', '2712', '2711', '1211', '1219', '3011'].includes(code)) branches.push('AUTO');
  if (['0004', '2006', '2715', '1399'].includes(code)) branches.push('RA');
  if (['2702', '2711', '0002'].includes(code)) branches.push('FT');
  if (['2006', '2718', '2739', '1113'].includes(code)) branches.push('CB');

  // De-duplicate
  branches = [...new Set(branches)];

  // Tuition fee depending on institution type (Tamil Nadu Govt fee structure)
  let annualFee = 55000;
  if (type === 'Government' || type === 'University Department' || type === 'Constituent College') {
    annualFee = 35000;
  } else if (type === 'Government Aided') {
    annualFee = isAuto ? 85000 : 55000;
  } else {
    // Self financing
    annualFee = isAuto ? 125000 : 85000;
  }

  branches.forEach(crs => {
    let intake = 60;
    if (['CSE', 'ECE'].includes(crs)) intake = isAuto ? 180 : 120;
    if (['AIDS', 'IT', 'MECH', 'EEE'].includes(crs)) intake = isAuto ? 120 : 60;

    COURSE_MAPPINGS.push({
      tnea_code: code,
      course_code: crs,
      intake: intake,
      annual_fee: annualFee,
      hostel_available: true,
      hostel_fee: type === 'Government' ? 30000 : 65000
    });
  });
});

// CSV Export Helper
function toCsv(data) {
  if (!data || !data.length) return '';
  const headers = Object.keys(data[0]);
  const rows = [headers.join(',')];
  for (const item of data) {
    const row = headers.map(h => {
      let val = item[h];
      if (val === null || val === undefined) return '';
      val = String(val);
      if (val.includes(',') || val.includes('"') || val.includes('\n')) {
        return '"' + val.replace(/"/g, '""') + '"';
      }
      return val;
    });
    rows.push(row.join(','));
  }
  return rows.join('\n');
}

